const DUNGEON: &[&str] = &[
    "##################################################",
    "#................................................#",
    "#................................................#",
    "#..............##########........................#",
    "#..............#........#........................#",
    "#..............#........#........................#",
    "#..............#........#........................#",
    "#..............##########........................#",
    "#................................................#",
    "#................................................#",
    "#................................................#",
    "##################################################",
];

fn main() {
    let player_x: usize = 5;
    let player_y: usize = 5;

    println!();
    println!("Terminal Roguelike");
    println!("------------------");
    println!();

    for (y, row) in DUNGEON.iter().enumerate() {
        for (x, tile) in row.chars().enumerate() {
            if x == player_x && y == player_y {
                print!("@");
            } else {
                print!("{tile}");
            }
        }

        println!();
    }

    println!();
    println!("@ = Player");
    println!("# = Wall");
    println!(". = Floor");
    println!();
    println!("Next milestone: player movement.");
}